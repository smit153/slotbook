/**
 * Turn loadtest/results/*.json (k6 summaries) + *.verify.json into loadtest/RESULTS.md.
 * Only numbers that are in those files; nothing is estimated.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

type Values = Record<string, number>;
interface Summary { metrics: Record<string, { values: Values }>; state: { testRunDurationMs: number } }

const root = resolve(import.meta.dirname, '../loadtest/results');
// The newest run folder (scripts/loadtest.sh writes one timestamped folder per run).
const latest = readdirSync(root).filter((d) => /^\d{8}T\d{6}Z$/.test(d)).sort().at(-1);
if (!latest) throw new Error('no results yet: run pnpm loadtest');
const dir = join(root, latest);
const order = (n: string) => (n.startsWith('many-') ? 0 : n.startsWith('busy') ? 1 : n === 'mixed' ? 2 : n.startsWith('pool30-many') ? 3 : 4) * 1e6 + (Number(n.match(/\d+$/)?.[0]) || 0);
const runs = readdirSync(dir).filter((f) => f.endsWith('.json') && !f.endsWith('.verify.json')).map((f) => f.slice(0, -5)).sort((a, b) => order(a) - order(b));

const ms = (v: number | undefined) => (v === undefined ? '–' : v >= 1000 ? `${(v / 1000).toFixed(2)} s` : `${Math.round(v)} ms`);
const n = (v: number | undefined) => (v === undefined ? 0 : Math.round(v));

const rows: string[] = [];
const latency: string[] = [];
for (const name of runs) {
  const s = JSON.parse(readFileSync(join(dir, `${name}.json`), 'utf8')) as Summary;
  const m = (k: string) => s.metrics[k]?.values;
  const secs = s.state.testRunDurationMs / 1000;
  const verifyFile = join(dir, `${name}.verify.json`);
  const verify = existsSync(verifyFile) ? (JSON.parse(readFileSync(verifyFile, 'utf8')) as { ok: boolean; checks: Record<string, number> }) : undefined;
  const reqs = m('http_reqs');
  rows.push(`| ${name} | ${secs.toFixed(0)} s | ${(m('iterations')?.rate ?? 0).toFixed(1)} | ${n(m('dropped_iterations')?.count)} | ${(reqs?.rate ?? 0).toFixed(1)} | ${n(m('bookings_confirmed')?.count)} (${((m('bookings_confirmed')?.count ?? 0) / secs).toFixed(1)}/s) | ${n(m('status_ok')?.count)} | ${n(m('status_409')?.count)} | ${n(m('status_503')?.count)} | ${n(m('status_410')?.count)} | ${n(m('status_429')?.count)} | **${n(m('real_errors')?.count)}** | ${verify ? (verify.ok ? '✅ 0 double bookings' : `❌ ${JSON.stringify(verify.checks)}`) : '–'} |`);
  const groups = name.includes('mixed') ? ['busy', 'background'] : [name.startsWith('busy') ? 'busy' : 'many'];
  for (const g of groups) {
    const d = (ep: string) => m(`http_req_duration{name:${ep},flow:${g}}`);
    latency.push(`| ${name}${groups.length > 1 ? ` (${g})` : ''} | ${(m(`iterations{flow:${g}}`)?.rate ?? 0).toFixed(1)} | ${ms(d('slots')?.med)} / ${ms(d('slots')?.['p(95)'])} | ${ms(d('hold')?.med)} / ${ms(d('hold')?.['p(95)'])} | ${ms(d('confirm')?.med)} / ${ms(d('confirm')?.['p(95)'])} | ${ms(d('hold')?.max)} |`);
  }
}

const env = existsSync(join(dir, 'env.txt')) ? readFileSync(join(dir, 'env.txt'), 'utf8').trim() : '';
const md = `# Load-test results

Generated by \`pnpm loadtest:report\` from the k6 summaries in \`loadtest/results/${latest}/\` (run with \`pnpm loadtest\`).
Database: ${env || 'see env.txt'}.

## Throughput and outcomes

One iteration = GET slots → POST hold → POST confirm (confirm only after a 201).
**409** = someone else got the slot (expected under contention). **503** = the designed fail-fast (\`HOST_BUSY\`/\`TRY_AGAIN\`).
**Dropped** = iterations k6 could not start on time at the requested arrival rate (the client side fell behind). **Real errors** = any other status (including every 5xx) or a network error. The last column is the read-only invariant check run after each run (seat counts, capacity, overlaps, double bookings).

| Run | Duration | Iterations/s | Dropped | Requests/s | Bookings confirmed | 2xx | 409 | 503 | 410 | 429 | Real errors | DB check |
|---|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Latency (median / p95 per endpoint)

| Run (flow) | Iterations/s | GET slots | POST hold | POST confirm | hold max |
|---|---|---|---|---|---|
${latency.join('\n')}
`;
writeFileSync(resolve(import.meta.dirname, '../loadtest/RESULTS.md'), md);
console.log(md);
